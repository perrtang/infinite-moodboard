const traditionalToSimplified = OpenCC.Converter({ from: "tw", to: "cn" });

function toSimplified(value) {
  let result = String(value);
  HANS_TERMS.forEach(([from, to]) => { result = result.replaceAll(from, to); });
  return traditionalToSimplified(result);
}

function translateEnglishCore(value) {
  if (EN_EXACT[value]) return EN_EXACT[value];
  for (const [pattern, replacement] of EN_PATTERNS) {
    if (pattern.test(value)) return value.replace(pattern, replacement);
  }
  return value;
}

export function translateInterfaceText(value, locale = activeInterfaceLocale) {
  if (value === null || value === undefined) return value;
  const normalizedLocale = normalizeInterfaceLocale(locale);
  const source = String(value);
  if (normalizedLocale === "zh-Hant" || !source.trim()) return source;
  const match = source.match(/^(\s*)([\s\S]*?)(\s*)$/);
  const leading = match?.[1] || "";
  const core = match?.[2] || source;
  const trailing = match?.[3] || "";
  const translated = normalizedLocale === "zh-Hans" ? toSimplified(core) : translateEnglishCore(core);
  return `${leading}${translated}${trailing}`;
}

