import OpenCC from "opencc-js/t2cn";

export const INTERFACE_LOCALE_STORAGE_KEY = "infinite-moodboard-interface-locale-v1";

export const INTERFACE_LOCALES = Object.freeze([
  { id: "zh-Hant", label: "繁體中文", shortLabel: "繁中" },
  { id: "zh-Hans", label: "简体中文", shortLabel: "简中" },
  { id: "en", label: "English", shortLabel: "EN" },
]);

const LOCALE_IDS = new Set(INTERFACE_LOCALES.map((locale) => locale.id));

export function normalizeInterfaceLocale(value) {
  const locale = String(value || "").trim();
  if (LOCALE_IDS.has(locale)) return locale;
  const normalized = locale.replaceAll("_", "-").toLowerCase();
  if (normalized === "zh-hant" || normalized.startsWith("zh-tw") || normalized.startsWith("zh-hk") || normalized.startsWith("zh-mo")) return "zh-Hant";
  if (normalized === "zh-hans" || normalized.startsWith("zh-cn") || normalized.startsWith("zh-sg") || normalized.startsWith("zh-my")) return "zh-Hans";
  return "en";
}

export function detectInterfaceLocale(languages = globalThis.navigator?.languages || [globalThis.navigator?.language]) {
  const values = Array.isArray(languages) ? languages : [languages];
  for (const value of values) {
    const normalized = String(value || "").toLowerCase();
    if (normalized.startsWith("zh")) return normalizeInterfaceLocale(value);
    if (normalized.startsWith("en")) return "en";
  }
  return "en";
}

export function loadInterfaceLocale(storage = globalThis.localStorage, languages) {
  try {
    const stored = storage?.getItem(INTERFACE_LOCALE_STORAGE_KEY);
    if (stored && LOCALE_IDS.has(stored)) return stored;
  } catch {
    // Storage can be unavailable in private or embedded browser contexts.
  }
  return detectInterfaceLocale(languages);
}

let activeInterfaceLocale = detectInterfaceLocale();

export function setActiveInterfaceLocale(locale) {
  activeInterfaceLocale = normalizeInterfaceLocale(locale);
  return activeInterfaceLocale;
}

export function getActiveInterfaceLocale() {
  return activeInterfaceLocale;
}

export function interfaceLocaleToIntl(locale = activeInterfaceLocale) {
  return { "zh-Hant": "zh-TW", "zh-Hans": "zh-CN", en: "en-US" }[normalizeInterfaceLocale(locale)];
}

