const originalText = new WeakMap();
const originalAttributes = new WeakMap();
const LOCALIZED_ATTRIBUTES = ["aria-label", "title", "placeholder", "data-placeholder"];

function shouldIgnore(element) {
  return !element
    || element.closest?.("[data-l10n-ignore], [contenteditable='true'], script, style, textarea")
    || ["SCRIPT", "STYLE", "TEXTAREA"].includes(element.tagName);
}

function localizeTextNode(node, locale) {
  const parent = node.parentElement;
  if (!parent || shouldIgnore(parent)) return;
  const current = node.nodeValue || "";
  let record = originalText.get(node);
  if (!record) record = { source: current, rendered: current };
  else if (current !== record.rendered) record.source = current;
  const next = translateInterfaceText(record.source, locale);
  record.rendered = next;
  originalText.set(node, record);
  if (current !== next) node.nodeValue = next;
}

function localizeAttributes(element, locale) {
  if (shouldIgnore(element)) return;
  let records = originalAttributes.get(element);
  if (!records) records = new Map();
  LOCALIZED_ATTRIBUTES.forEach((name) => {
    if (!element.hasAttribute?.(name)) return;
    const current = element.getAttribute(name) || "";
    let record = records.get(name);
    if (!record) record = { source: current, rendered: current };
    else if (current !== record.rendered) record.source = current;
    const next = translateInterfaceText(record.source, locale);
    record.rendered = next;
    records.set(name, record);
    if (current !== next) element.setAttribute(name, next);
  });
  originalAttributes.set(element, records);
}

function walkAndLocalize(root, locale) {
  if (!root) return;
  if (root.nodeType === Node.TEXT_NODE) {
    localizeTextNode(root, locale);
    return;
  }
  if (root.nodeType !== Node.ELEMENT_NODE) return;
  localizeAttributes(root, locale);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    if (node.nodeType === Node.TEXT_NODE) localizeTextNode(node, locale);
    else localizeAttributes(node, locale);
    node = walker.nextNode();
  }
}

export function localizeInterfaceDom(root, locale) {
  const normalizedLocale = setActiveInterfaceLocale(locale);
  if (!root || typeof MutationObserver !== "function") return () => {};
  walkAndLocalize(root, normalizedLocale);
  const observer = new MutationObserver((mutations) => {
    mutations.forEach((mutation) => {
      if (mutation.type === "characterData") localizeTextNode(mutation.target, normalizedLocale);
      if (mutation.type === "attributes") localizeAttributes(mutation.target, normalizedLocale);
      mutation.addedNodes?.forEach((node) => walkAndLocalize(node, normalizedLocale));
    });
  });
  observer.observe(root, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: LOCALIZED_ATTRIBUTES,
  });
  return () => observer.disconnect();
}

